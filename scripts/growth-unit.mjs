import assert from 'node:assert/strict';
import {createWorker,validateMetric} from '../worker/measure.mjs';
const allow={pages:new Set(['/']),products:new Set(['/products/example'])};
const base={version:1,consent:true,event:'page_view',page:'/',source:'tiktok',campaign:'gshock-noire',placement:'page'};
assert.ok(validateMetric(base,allow));
for(const patch of [{consent:false},{event:'sale'},{page:'/?email=private'},{email:'private'},{source:'arbitrary'},{count:4},{product:'/products/fake'},{version:2}])assert.equal(validateMetric({...base,...patch},allow),null);
const logs=[];const worker=createWorker({pages:['/'],products:['/products/example']},{log:m=>logs.push(m)});
const request=(body,headers={})=>new Request('https://cadrin.fr/api/measure',{method:'POST',headers:{Origin:'https://cadrin.fr','Sec-Fetch-Site':'same-origin','Content-Type':'application/json',...headers},body:typeof body==='string'?body:JSON.stringify(body)});
assert.equal((await worker.fetch(request(base))).status,204);
assert.equal(logs.length,1);assert.ok(!JSON.stringify(logs).includes('consent'));
assert.equal((await worker.fetch(request(base,{Origin:'https://evil.example'}))).status,403);
assert.equal((await worker.fetch(request(base,{'Content-Type':'text/plain'}))).status,415);
assert.equal((await worker.fetch(request('x'.repeat(1025)))).status,413);
assert.equal((await worker.fetch(request('{broken'))).status,400);
assert.equal((await worker.fetch(new Request('https://cadrin.fr/api/measure'))).status,405);
assert.equal(logs.length,1);
assert.equal((await createWorker({pages:[],products:[]},{enabled:false}).fetch(request(base))).status,404);
const asset=await worker.fetch(new Request('https://cadrin.fr/missing'),{ASSETS:{fetch:()=>new Response('asset')}});assert.equal(await asset.text(),'asset');
console.log('PASS: metric allowlists, consent, origin, JSON, bounded stream, preview disabled, static fallback');
